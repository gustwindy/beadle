CREATE TABLE IF NOT EXISTS sessions (
	sessionKey TEXT PRIMARY KEY UNIQUE,
	expiresAt INTEGER NOT NULL,
	userId TEXT NOT NULL,

	FOREIGN KEY (userId) REFERENCES users(id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS users (
	id TEXT PRIMARY KEY UNIQUE,
	username TEXT NOT NULL,
	displayName TEXT NOT NULL,

	serverJoinDate INTEGER NOT NULL,
	avatarHash TEXT NOT NULL,

	streak INTEGER NOT NULL DEFAULT 0,
	isAdmin BOOLEAN NOT NULL DEFAULT false,

	lastPlaySession TEXT NOT NULL DEFAULT "{}",
	settings TEXT NOT NULL DEFAULT "{}"
);

CREATE TABLE IF NOT EXISTS codeCollection (
	code TEXT PRIMARY KEY,
	sessionKey TEXT NOT NULL,
	expiresAt INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS artists (
    userId TEXT PRIMARY KEY UNIQUE NOT NULL,
    commonName TEXT NOT NULL,
    aliases TEXT NOT NULL DEFAULT "[]"
);

CREATE TABLE IF NOT EXISTS drawings (
    imageHash TEXT PRIMARY KEY UNIQUE NOT NULL,
    artistId TEXT NOT NULL,

	FOREIGN KEY (artistId) REFERENCES artists(id) ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS history (
    day INTEGER PRIMARY KEY UNIQUE NOT NULL,
    time INTEGER UNIQUE NOT NULL,
	drawingId TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS forced (
    thisShouldBe0 INTEGER PRIMARY KEY UNIQUE NOT NULL,
	drawingId TEXT NOT NULL
);
